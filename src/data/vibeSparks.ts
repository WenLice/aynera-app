const FALLBACK = "✨\nThis one says something about you.\n\nWe noticed. 🤍";

export function sparkForChip(option: string): string {
  return VIBE_SPARKS[option] ?? FALLBACK;
}

/** Emoji headline + body, split for layout. */
export function splitSpark(spark: string): { emoji: string; body: string } {
  const lines = spark.split("\n");
  const first = lines[0]?.trim() ?? "";
  const isEmojiLine = first.length > 0 && first.length <= 6 && !/[a-zA-Z]/.test(first);
  if (!isEmojiLine) return { emoji: "✨", body: spark.trim() };
  return { emoji: first, body: lines.slice(1).join("\n").trim() };
}
